const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const modules = {
  content: 'miniprogram/data/content.js',
  core: 'miniprogram/engine/core.js',
  choicelog: 'miniprogram/engine/choicelog.js',
  random: 'miniprogram/engine/random.js',
  renderer: 'miniprogram/engine/renderer.js',
  world: 'miniprogram/engine/world.js'
};
let output = '/* Auto-generated by scripts/build-web.js. Edit the source modules instead. */\n';
output += 'window.CampusRequire = (() => {\nconst modules = {};\nconst cache = {};\n';
Object.entries(modules).forEach(([id, file]) => {
  const source = fs.readFileSync(path.join(root, file), 'utf8')
    .replace(/require\(['"]\.\.\/data\/content['"]\)/g, "require('content')")
    .replace(/require\(['"]\.\/random['"]\)/g, "require('random')");
  output += `modules['${id}'] = function(module, exports, require) {\n${source}\n};\n`;
});
output += `function require(id) { if (cache[id]) return cache[id].exports; const module = { exports: {} }; cache[id] = module; modules[id](module, module.exports, require); return module.exports; }\nreturn require;\n})();`;
fs.writeFileSync(path.join(root, 'web/bundle.js'), output);

/* 给 index.html 里的脚本加上内容指纹：
   浏览器会把旧的 bundle.js 留在缓存/已打开的标签里，改了代码却还在跑旧逻辑，
   表现就是「明明改了却没生效」。每次构建换一个 ?v=，刷新才会真的拿新代码。 */
const hash = require('crypto').createHash('md5').update(output).digest('hex').slice(0, 8);
const indexPath = path.join(root, 'web/index.html');
let html = fs.readFileSync(indexPath, 'utf8');
html = html
  .replace(/bundle\.js(\?v=[0-9a-z]+)?/g, `bundle.js?v=${hash}`)
  .replace(/app\.js(\?v=[0-9a-z]+)?/g, `app.js?v=${hash}`);
fs.writeFileSync(indexPath, html);

console.log(`Built web/bundle.js from shared game modules. (v=${hash})`);
